    IDCT_transform(coef, data, index, nBlock) {

        var FIX_1_082392200  = (277);     /* FIX(1.082392200) */
        var FIX_1_414213562  = (362);     /* FIX(1.414213562) */
        var FIX_1_847759065  = (473);     /* FIX(1.847759065) */
        var FIX_2_613125930  = (669);     /* FIX(2.613125930) */

        var tmp0, tmp1, tmp2, tmp3, tmp4, tmp5, tmp6, tmp7;
        var tmp10, tmp11, tmp12, tmp13;
        var z5, z10, z11, z12, z13;

        var inptr = coef;
        var quantptr = null;
        var wsptr = this.mWorkspace;
        var outptr;
        var ctr, dcval;

        quantptr = this.mQT [nBlock];
        //Pass 1: process columns from input (inptr), store into work array(wsptr)

        var ptr_index = 0;
        for (ctr = 0; ctr < 8; ctr++) {
            /* Due to quantization, we will usually find that many of the input
             * coefficients are zero, especially the AC terms.  We can exploit this
             * by short-circuiting the IDCT calculation for any column in which all
             * the AC terms are zero.  In that case each output is equal to the
             * DC coefficient (with scale factor as needed).
             * With typical images and quantization tables, half or more of the
             * column DCT calculations can be simplified this way.
             */
            if ((inptr [index + ctr + 8 ]
               | inptr [index + ctr + 16]
               | inptr [index + ctr + 24]
               | inptr [index + ctr + 32]
               | inptr [index + ctr + 40]
               | inptr [index + ctr + 48]
               | inptr [index + ctr + 56]
                  ) == 0) {
                /* AC terms all zero */
                dcval = 0xffffffff & ((inptr [index + ctr] * quantptr [ctr]) >> 16);

                wsptr [ctr     ] = dcval;
                wsptr [ctr + 8 ] = dcval;
                wsptr [ctr + 16] = dcval;
                wsptr [ctr + 24] = dcval;
                wsptr [ctr + 32] = dcval;
                wsptr [ctr + 40] = dcval;
                wsptr [ctr + 48] = dcval;
                wsptr [ctr + 56] = dcval;

                continue;
            }

            /* Even part */

            tmp0 = (inptr [index + ctr      ] * quantptr [ctr     ]) >> 16;
            tmp1 = (inptr [index + ctr +  16] * quantptr [ctr + 16]) >> 16;
            tmp2 = (inptr [index + ctr +  32] * quantptr [ctr + 32]) >> 16;
            tmp3 = (inptr [index + ctr +  48] * quantptr [ctr + 48]) >> 16;

            tmp10 = tmp0 + tmp2; /* phase 3 */
            tmp11 = tmp0 - tmp2;

            tmp13 = tmp1 + tmp3; /* phases 5-3 */
            tmp12 = this.MULTIPLY(tmp1 - tmp3, FIX_1_414213562) - tmp13; /* 2*c4 */

            tmp0 = tmp10 + tmp13; /* phase 2 */
            tmp3 = tmp10 - tmp13;
            tmp1 = tmp11 + tmp12;
            tmp2 = tmp11 - tmp12;

            /* Odd part */

            tmp4 = (inptr [index + ctr + 8 ] * quantptr [ctr + 8 ]) >> 16;
            tmp5 = (inptr [index + ctr + 24] * quantptr [ctr + 24]) >> 16;
            tmp6 = (inptr [index + ctr + 40] * quantptr [ctr + 40]) >> 16;
            tmp7 = (inptr [index + ctr + 56] * quantptr [ctr + 56]) >> 16;

            z13 = tmp6 + tmp5; /* phase 6 */
            z10 = tmp6 - tmp5;
            z11 = tmp4 + tmp7;
            z12 = tmp4 - tmp7;

            tmp7 = z11 + z13; /* phase 5 */
            tmp11 = this.MULTIPLY(z11 - z13, FIX_1_414213562); /* 2*c4 */

            z5 = this.MULTIPLY(z10 + z12, FIX_1_847759065); /* 2*c2 */
            tmp10 = this.MULTIPLY(z12, FIX_1_082392200) - z5; /* 2*(c2-c6) */
            tmp12 = this.MULTIPLY(z10, - FIX_2_613125930) + z5; /* -2*(c2+c6) */

            tmp6 = tmp12 - tmp7; /* phase 2 */
            tmp5 = tmp11 - tmp6;
            tmp4 = tmp10 + tmp5;

            wsptr [ctr     ] = (tmp0 + tmp7);
            wsptr [ctr + 56] = (tmp0 - tmp7);
            wsptr [ctr + 8 ] = (tmp1 + tmp6);
            wsptr [ctr + 48] = (tmp1 - tmp6);
            wsptr [ctr + 16] = (tmp2 + tmp5);
            wsptr [ctr + 40] = (tmp2 - tmp5);
            wsptr [ctr + 32] = (tmp3 + tmp4);
            wsptr [ctr + 24] = (tmp3 - tmp4);

        }

        /* Pass 2: process rows from work array, store into output array. */
        /* Note that we must descale the results by a factor of 8 == 2**3, */
        /* and also undo the PASS1_BITS scaling. */

        //#define RANGE_MASK 1023; //2 bits wider than legal samples
        var IDESCALE = function(x,n)  {return (((x)>>n) );};
        "use strict";

        // wsptr = workspace;
        // ptr_index = 0;
        outptr = data;
        var outptr_index;
        // for (ctr = 0; ctr < DCTSIZE; ctr++) {
        for (ctr = 0; ctr < 8; ctr++) {
            // outptr = data + ctr * 8;
            outptr_index = ctr * 8;

            /* Rows of zeroes can be exploited in the same way as we did with columns.
            * However, the column calculation has created many nonzero AC terms, so
            * the simplification applies less often (typically 5% to 10% of the time).
            * On machines with very fast multiplication, it's possible that the
            * test takes more time than it's worth.  In that case this section
            * may be commented out.
            */
            /* Even part */

            tmp10 = ( wsptr[ outptr_index +0] + wsptr[ outptr_index +4]);
            tmp11 = ( wsptr[ outptr_index +0] - wsptr[ outptr_index +4]);
            tmp13 = ( wsptr[ outptr_index +2] + wsptr[ outptr_index +6]);
            tmp12 = this.MULTIPLY( wsptr[ outptr_index +2] - wsptr[ outptr_index +6], FIX_1_414213562) - tmp13;

            tmp0 = tmp10 + tmp13;
            tmp3 = tmp10 - tmp13;
            tmp1 = tmp11 + tmp12;
            tmp2 = tmp11 - tmp12;

            /* Odd part */

            z13 = wsptr[ outptr_index +5] + wsptr[ outptr_index +3];
            z10 = wsptr[ outptr_index +5] - wsptr[ outptr_index +3];
            z11 = wsptr[ outptr_index +1] + wsptr[ outptr_index +7];
            z12 = wsptr[ outptr_index +1] - wsptr[ outptr_index +7];

            tmp7 = z11 + z13; /* phase 5 */
            tmp11 = this.MULTIPLY(z11 - z13, FIX_1_414213562); /* 2*c4 */

            z5 = this.MULTIPLY(z10 + z12, FIX_1_847759065); /* 2*c2 */
            tmp10 = this.MULTIPLY(z12, FIX_1_082392200) - z5; /* 2*(c2-c6) */
            tmp12 = this.MULTIPLY(z10, - FIX_2_613125930) + z5; /* -2*(c2+c6) */

            tmp6 = tmp12 - tmp7; /* phase 2 */
            tmp5 = tmp11 - tmp6;
            tmp4 = tmp10 + tmp5;

            /* Final output stage: scale down by a factor of 8 and range-limit */

            outptr [index + outptr_index + 0] = this.mRlimitTable [384 +IDESCALE((tmp0 + tmp7), (3)) & 0x3ff];
            outptr [index + outptr_index + 7] = this.mRlimitTable [384 +IDESCALE((tmp0 - tmp7), (3)) & 0x3ff];
            outptr [index + outptr_index + 1] = this.mRlimitTable [384 +IDESCALE((tmp1 + tmp6), (3)) & 0x3ff];
            outptr [index + outptr_index + 6] = this.mRlimitTable [384 +IDESCALE((tmp1 - tmp6), (3)) & 0x3ff];
            outptr [index + outptr_index + 2] = this.mRlimitTable [384 +IDESCALE((tmp2 + tmp5), (3)) & 0x3ff];
            outptr [index + outptr_index + 5] = this.mRlimitTable [384 +IDESCALE((tmp2 - tmp5), (3)) & 0x3ff];
            outptr [index + outptr_index + 4] = this.mRlimitTable [384 +IDESCALE((tmp3 + tmp4), (3)) & 0x3ff];
            outptr [index + outptr_index + 3] = this.mRlimitTable [384 +IDESCALE((tmp3 - tmp4), (3)) & 0x3ff];
        }
    }

    updatereadbuf (walks) {
        var readbuf;
        if (walks == undefined)
            Util.Error("walks is undefined");
        var newbits = this.mNewbits - walks;
        if ((newbits) <= 0){
            readbuf = this.get_qbytes_from_mBuffer(4);
            this.mCodebuf = (this.mCodebuf << walks) | ((this.mNewbuf | (readbuf >>> (this.mNewbits))) >>> 32 - walks);
            this.mNewbuf = readbuf << (walks - this.mNewbits);
            this.mNewbits = 32 + newbits;
        } else {
            this.mCodebuf = (this.mCodebuf << walks) | (this.mNewbuf >>> (32 - walks));
            this.mNewbuf = this.mNewbuf << walks;
            this.mNewbits = newbits;
        }

    }

