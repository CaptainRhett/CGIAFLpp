    getKbits(k) {
      var signed_wordvalue;

      //river
      signed_wordvalue = 0xffff & (this.mCodebuf >>> (32 - k));
      if (((0x1 << (k - 1)) & signed_wordvalue) == 0)
        signed_wordvalue = signed_wordvalue + this.mNegPow2 [k];

      this.skipKbits (k);
      return signed_wordvalue;
    }

