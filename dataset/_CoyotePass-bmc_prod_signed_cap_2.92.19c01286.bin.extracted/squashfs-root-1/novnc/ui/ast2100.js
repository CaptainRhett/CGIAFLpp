        this.load_Huffman_table = function(HT, nrcode, value, Huff_code) {
            "use strict";
            var k, j, i;
            var code_index;
            var code;

            for (j = 1; j <= 16; j++) {
                HT.table_length[j] = nrcode[j];
            }
            for (i = 0, k = 1; k <=16; k++) {
                for (j = 0; j < HT.table_length[k]; j++) {
                    HT.V[this.WORD_hi_lo(k, j)] = value[i];
                    i++;
                }
            }

            code = 0;
            for (k = 1; k <= 16; k++) {
                HT.minor_code [k] = 0xffff & code;
                for (j = 1; j <= HT.table_length [k]; j++)
                  code++;
                HT.major_code [k] = 0xffff & (code - 1);
                code *= 2;
                if (HT.table_length [k] == 0) {
                  HT.minor_code [k] = 0xFFFF;
                  HT.major_code [k] = 0;
                }
            }

            HT.table_len[0] = 2;
            i = 2;

            for (code_index = 1; code_index <65535; code_index++) {
                if (code_index < Huff_code [i]) {
                    HT.table_len[code_index] = 0xFF & Huff_code [ i + 1];
                } else {
                    i = i + 2;
                    HT.table_len[code_index] = 0xFF & Huff_code [ i + 1];
                }
            }
            return 0;
        };

