    _keymap (keysym, down, kb) {
        var keymap = this.Keymap;
        var keymap_keysym = null;
        for (var i=0; i< keymap.length; i++) {
            if (keymap[i][0] == keysym) {
                keymap_keysym = keymap[i][1];
                break;
            }
        }
        if (keymap_keysym == null) {
            console.log("keysym: " + keysym.toString(16) + " can't not found in keymap");
        }
        if (kb) {
            var key_lock_event = 0;
            var KeyCapsLk = 0;
            var KeyNumLk = 0;
            var KeyScrollLk = 0;
            KeyCapsLk = kb.getCapsLk();
            KeyNumLk = kb.getNumLk();
            KeyScrollLk = kb.getScrollLk();
            if (keysym == KeyTable.XK_Caps_Lock) {
                if (KeyCapsLk) {
                    keymap_keysym |= (0xff << 8);
                }
                if (!down) {
                    KeyCapsLk = !KeyCapsLk;
                    key_lock_event = 1;
                }
            } else if (keysym == KeyTable.XK_Num_Lock) {
                if (KeyNumLk) {
                    keymap_keysym |= (0xff << 8);
                }
                if (!down) {
                    KeyNumLk = !KeyNumLk;
                    key_lock_event = 1;
                }
            } else if (keysym == KeyTable.XK_Scroll_Lock) {
                if (KeyScrollLk) {
                    keymap_keysym |= (0xff << 8);
                }
                if (!down) {
                    KeyScrollLk = !KeyScrollLk;
                    key_lock_event = 1;
                }
            }
            if ((key_lock_event)&&(kb)) {
                var status = (KeyNumLk) | (KeyCapsLk<<1) | (KeyScrollLk<<2);
                kb.setLedStatus(status);
            }
        } else {
            console.log("keyEventInsyde kb is undefined");
        }
        return keymap_keysym;
    }

